export function getCoords(codePostal) {
  const cp = parseInt(codePostal, 10);
  if (!cp) return null;

  // Recherche exacte
  if (POSTAL_COORDS[cp]) {
    const [lat, lng] = POSTAL_COORDS[cp];
    return { lat, lng };
  }

  // Fallback province
  const prov = PROVINCE_FALLBACK.find(p => cp >= p.range[0] && cp <= p.range[1]);
  if (prov) return { lat: prov.lat, lng: prov.lng };

  return null;
}
